# --- reading the sources ----------------------------------------------------

# A BibTeX entry head: "@article{Key," at the start of a line.  Comment lines in
# refs.bib carry no "@" precisely so that BibTeX itself does not mistake one for
# an entry, and this pattern inherits that guarantee.
ENTRY = re.compile(r'^@(\w+)\s*\{\s*([^,\s]+)\s*,', re.M)

# \cite{a,b}, \citep[see][]{a}, \citet{a}, \nocite{a}.  "*" is not a key.
CITE = re.compile(r'\\(?:no)?cite[a-zA-Z]*\s*(?:\[[^\]]*\]\s*){0,2}\{([^}]*)\}')

FIELD = re.compile(r'^\s*(\w+)\s*=\s*[{"]', re.M)


def _strip_tex_comments(text):
    """Drop everything after an unescaped % on each line."""
    out = []
    for line in text.split("\n"):
        i, keep = 0, line
        while i < len(line):
            if line[i] == "%" and (i == 0 or line[i - 1] != "\\"):
                keep = line[:i]
                break
            i += 1
        out.append(keep)
    return "\n".join(out)


# The letter's own bibliography, and the reserve beside it.  refs.bib is kept
# in exact correspondence with main.tex's \cite commands; refs_reserve.bib
# holds the records that cover the two source reference lists and that the
# letter does not cite, and only draft mode compiles it.
BIB = "refs.bib"
RESERVE = "refs_reserve.bib"


def _bib_entries(name=BIB):
    """[(kind, key, body)] for one bibliography file, in file order."""
    path = PAPER / name
    if not path.exists():
        return []
    text = path.read_text(encoding="utf-8")
    heads = list(ENTRY.finditer(text))
    entries = []
    for i, m in enumerate(heads):
        end = heads[i + 1].start() if i + 1 < len(heads) else len(text)
        entries.append((m.group(1).lower(), m.group(2), text[m.start():end]))
    return entries


# main.tex guards its draft bibliography with \ifdraftbib ... \else ... \fi:
# draft mode adds refs_reserve.bib and emits \nocite{*} so that a build checks
# that every record of both files parses, and the letter itself is built with
# \draftbibfalse and compiles refs.bib alone.  A \nocite{*} sitting in the
# branch that is switched off is not a citation of everything, and reading it
# as one would switch off the two directions checked below, so the conditional
# is resolved the way TeX would resolve it before the keys are collected.
# (the lookbehind keeps \newif\ifdraftbib, which declares the switch and
# opens no conditional, from being read as the start of one)
_DRAFT_SPAN = re.compile(r"(?<!\\newif)\\ifdraftbib(.*?)\\fi", re.S)
_DRAFT_SET = re.compile(r"\\draftbib(true|false)\b")


def _draft_bib(body):
    """Is \draftbibtrue the setting in force?  (comments already removed)"""
    settings = _DRAFT_SET.findall(body)
    return bool(settings) and settings[-1] == "true"


def _resolve_draft(body):
    draft = _draft_bib(body)

    def take(m):
        branches = m.group(1).split(r"\else", 1)
        if draft:
            return branches[0]
        return branches[1] if len(branches) > 1 else " "
    return _DRAFT_SPAN.sub(take, body)


def _cite_keys():
    """Every key cited by paper/main.tex, comments removed and the draft
    bibliography switch resolved.  A live \nocite{*} -> (keys, True)."""
    path = PAPER / "main.tex"
    if not path.exists():
        return set(), False
    body = _resolve_draft(_strip_tex_comments(path.read_text(encoding="utf-8")))
    keys, star = set(), False
    for m in CITE.finditer(body):
        for k in m.group(1).split(","):
            k = k.strip()
            if k == "*":
                star = True
            elif k:
                keys.add(k)
    return keys, star


def _fig_register():
    """[(label, script)] read out of the table in paper/figs/README.md."""
    path = PAPER / "figs/README.md"
    if not path.exists():
        return []
    rows = []
    for line in path.read_text(encoding="utf-8").split("\n"):
        if not line.startswith("| Fig."):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3:
            continue
        m = re.search(r'`([^`]+\.py)`', cells[2])
        if m:
            pub = re.search(r'`([^`]+\.png)`', cells[3]) if len(cells) > 3 else None
            rows.append((cells[0], m.group(1),
                         pub.group(1) if pub else None))
    return rows


# --- coverage of the two source reference lists -----------------------------

# Every entry of refs.bib carries a "% cited by ..." comment naming the entries
# of the two source lists it came from: R1[n] for
# reports/cos2phi_money_plots_report.template.html and N[n] for
# docs/note_cos2phi_coherent_6Li.md.  That comment is what makes "0 unresolved"
# a statement about the letter's sources rather than about its own \cite
# commands, which the skeleton has none of yet.
CITED_BY = re.compile(r'^%\s*cited by\s+(.+)$', re.M)
LABEL = re.compile(r'(R1|N)\[(\d+)\]')

REPORT1 = "reports/cos2phi_money_plots_report.template.html"
NOTE = "docs/note_cos2phi_coherent_6Li.md"


def _source_list_sizes():
    """(n_report1, n_note): how many numbered entries each source list has."""
    n1 = n2 = 0
    p1 = ROOT / REPORT1
    if p1.exists():
        text = p1.read_text(encoding="utf-8")
        m = re.search(r'<div\s+class="refs[^"]*">(.*?)</div>', text, re.S)
        if m:
            n1 = len(set(int(x) for x in
                         re.findall(r'<p>\s*\[(\d+)\]', m.group(1))))
    p2 = ROOT / NOTE
    if p2.exists():
        text = p2.read_text(encoding="utf-8")
        m = re.search(r'^## References\s*$(.*?)^## ', text, re.S | re.M)
        body = m.group(1) if m else ""
        n2 = len(set(int(x) for x in re.findall(r'^\[(\d+)\]', body, re.M)))
    return n1, n2


def _covered_labels():
    """The (list, number) pairs both bibliography files account for."""
    labels, n = set(), 0
    for name in (BIB, RESERVE):
        path = PAPER / name
        if not path.exists():
            continue
        for m in CITED_BY.finditer(path.read_text(encoding="utf-8")):
            n += 1
            for kind, num in LABEL.findall(m.group(1)):
                labels.add((kind, int(num)))
    return labels, n


def _coverage_issues():
    """Every numbered entry of both source lists is represented in the two
    bibliography files together."""
    entries = _bib_entries() + _bib_entries(RESERVE)
    labels, n_comments = _covered_labels()
    bad = []
    if n_comments != len(entries):
        bad.append("%d of %d entries of refs.bib and %s carry a "
                   "'%% cited by' comment" % (n_comments, len(entries), RESERVE))
    n1, n2 = _source_list_sizes()
    if n1 == 0:
        bad.append("could not read the reference list of %s" % REPORT1)
    if n2 == 0:
        bad.append("could not read the reference list of %s" % NOTE)
    for kind, n, where in (("R1", n1, REPORT1), ("N", n2, NOTE)):
        missing = [i for i in range(1, n + 1) if (kind, i) not in labels]
        if missing:
            bad.append("%s: entries %s are cited by no record of refs.bib or "
                       "%s" % (where, ", ".join("[%d]" % i for i in missing),
                               RESERVE))
    return bad


# --- the checks -------------------------------------------------------------

def _scaffold_issues():
    if not PAPER.is_dir():
        return ["paper/ does not exist"]
    return ["paper/%s is missing" % f for f in REQUIRED
            if not (PAPER / f).exists()]


def _bib_issues():
    """The two directions between main.tex and refs.bib, plus duplicate keys.

    Returns (issues, n_cited, n_unresolved), where "unresolved" counts both
    directions: a \cite with no entry, and an entry with no \cite.  The
    second direction is what keeps refs.bib shippable -- it is the file that
    goes to the journal, and a record in it that nothing cites is either a
    citation dropped from the text or a reserve record that strayed out of
    refs_reserve.bib.  The reserve is exempt by living in that other file,
    which main.tex compiles only under \draftbibtrue.
    """
    entries = _bib_entries()
    if not entries:
        return (["paper/refs.bib holds no BibTeX entry"], 0, 0)
    bad = []
    seen = {}
    for _, key, _ in entries:
        if key in seen:
            bad.append("duplicate key %s in refs.bib" % key)
        seen[key] = True
    reserve = {}
    for _, key, _ in _bib_entries(RESERVE):
        if key in reserve:
            bad.append("duplicate key %s in %s" % (key, RESERVE))
        if key in seen:
            bad.append("%s is in refs.bib and in %s: BibTeX would take "
                       "whichever it read first" % (key, RESERVE))
        reserve[key] = True
    cited, star = _cite_keys()
    unresolved = sorted(k for k in cited if k not in seen)
    for k in unresolved:
        if k in reserve:
            bad.append(r"\cite{%s} in main.tex resolves only in %s: move that "
                       "entry into refs.bib, which is the file the letter "
                       "compiles" % (k, RESERVE))
        else:
            bad.append(r"\cite{%s} in main.tex resolves to no refs.bib entry"
                       % k)
    uncited = sorted(k for k in seen if k not in cited)
    if not star:
        for k in uncited:
            bad.append("refs.bib entry %s is reached by no \cite in main.tex: "
                       "either cite it or move it to %s" % (k, RESERVE))
    unresolved = unresolved + ([] if star else uncited)
    # The budget survives beside the correspondence: plans/07 SS 7.2 gives the
    # letter ~40 references and the WP6 brief caps it at MAX_CITED, and a
    # letter that silently grew past that would be a different document.
    if not star and cited and len(cited) > MAX_CITED:
        bad.append("main.tex cites %d distinct works; plans/07 SS 7.2 budgets "
                   "at most %d for a letter" % (len(cited), MAX_CITED))
    if not star and not cited:
        bad.append("main.tex cites nothing and does not run with "
                   r"\draftbibtrue: the bibliography would be empty")
    return (bad, len(cited), len(unresolved))


def _provenance_issues():
    """Every entry of either file is INSPIRE-shaped or flagged hand-written."""
    bad = []
    for kind, key, body in _bib_entries() + _bib_entries(RESERVE):
        fields = set(f.lower() for f in FIELD.findall(body))
        hand = "HAND-WRITTEN" in body
        if hand:
            if kind != "misc":
                bad.append("%s is flagged HAND-WRITTEN but is @%s, not @misc"
                           % (key, kind))
            if "note" not in fields:
                bad.append("%s is flagged HAND-WRITTEN outside a note field" % key)
            continue
        # a machine-fetched INSPIRE record always carries at least one of these
        if not fields & {"eprint", "doi", "journal", "reportnumber"}:
            bad.append("%s has no eprint, doi, journal or reportNumber, and is "
                       "not flagged HAND-WRITTEN -- was it typed by hand?" % key)
        if "title" not in fields or "author" not in fields:
            bad.append("%s is missing a title or an author field" % key)
    prov = PAPER / "refs_provenance.md"
    if prov.exists():
        text = prov.read_text(encoding="utf-8")
        for _, key, body in _bib_entries() + _bib_entries(RESERVE):
            if "HAND-WRITTEN" in body and key not in text:
                bad.append("hand-written entry %s is not accounted for in "
                           "refs_provenance.md" % key)
    return bad


def _figure_issues():
    rows = _fig_register()
    if len(rows) != 4:
        return ["paper/figs/README.md registers %d letter figures, expected 4"
                % len(rows)]
    bad = []
    for label, script, _pub in rows:
        if not (ROOT / script).exists():
            bad.append("%s names producing script %s, which does not exist"
                       % (label, script))
    return bad


def _frontmatter_issues():
    path = PAPER / "main.tex"
    if not path.exists():
        return ["paper/main.tex is missing"]
    text = path.read_text(encoding="utf-8")
    bad = []
    # the programme's author line, affiliation and writing-assistance line --
    # required of everything paper-like in this repository
    for needle, what in (
            (r"\author[anl]{C.~Peng}", "the C. Peng author line"),
            (r"\author[anl]{J.~Zhou}", "the J. Zhou author line"),
            ("Physics Division, Argonne National Laboratory", "the ANL affiliation"),
            ("Writing assisted by Claude (Anthropic)", "the writing-assistance line"),
    ):
        if needle not in text:
            bad.append("main.tex does not carry %s" % what)
    # plans/07 WP6 asks for "elsarticle, two-column" and does not choose
    # between the journal layout and the preprint one.  main.tex carries both
    # class lines, one active and one commented, so that the letter can be read
    # in either; the check is that the active one is an elsarticle two-column
    # line and that the alternative is still recorded.
    active = [ln.strip() for ln in text.split("\n")
              if ln.strip().startswith(r"\documentclass")]
    if len(active) != 1:
        bad.append("main.tex has %d uncommented \\documentclass line(s), "
                   "expected exactly 1" % len(active))
    elif "elsarticle" not in active[0] or "twocolumn" not in active[0]:
        bad.append("main.tex's class line %r is not an elsarticle two-column "
                   "line, which plans/07 WP6 asks for" % active[0])
    for spelling in ("[final,5p,times,twocolumn]{elsarticle}",
                     "[preprint,twocolumn,12pt]{elsarticle}"):
        if spelling not in text:
            bad.append("main.tex no longer records the %s layout; both belong "
                       "in the file, one active and one commented" % spelling)
    return bad


# --- the built letter figures and Table 1 (T25) -----------------------------

# Stem -> the caption macro main.tex writes in that figure's \caption{}.  The
# drivers emit the \newcommand; main.tex \input{}s it.  Spelled out rather
# than derived because main.tex names them in words.
CAPTION_MACRO = {
    "fig1": "figonecaption",
    "fig2": "figtwocaption",
    "fig3": "figthreecaption",
    "fig4": "figfourcaption",
}

# Every file `paper/build.sh` is required to (re)generate.  These are committed
# artifacts, not build litter -- paper/.gitignore covers the LaTeX droppings
# only -- so the sweep can insist on them the same way it insists on the
# published PNGs of evgen/.
def _build_products():
    out = []
    for stem in sorted(CAPTION_MACRO):
        for suffix in (".pdf", ".png", ".json", "_caption.tex"):
            out.append("figs/%s%s" % (stem, suffix))
    out += ["table1.tex", "figs/table1.json"]
    return out


def _missing_products():
    return [f for f in _build_products() if not (PAPER / f).exists()]


def _load_json(rel):
    import json
    return json.loads((PAPER / rel).read_text(encoding="utf-8"))


# A generated tabular row: "cell & cell & ... \\" .  \midrule, \toprule and
# the \multicolumn section headings are not rows of numbers and are skipped.
def _tex_rows(text):
    rows = []
    for line in text.split("\n"):
        s = line.strip()
        if not s.endswith(r"\\") or s.startswith("%"):
            continue
        s = s[:-2].strip()
        if s.startswith(r"\multicolumn") or "&" not in s:
            continue
        cells = [c.strip() for c in s.split("&")]
        if any(c.startswith(r"\toprule") for c in cells):
            continue
        rows.append(cells)
    return rows


# The header row names the columns; it is the one tabular row whose first cell
# is not a bin.  Dropped by matching the JSON's row count from the end.
def _table_issues():
    missing = _missing_products()
    if missing:
        return ["paper/%s is missing: run `bash paper/build.sh --figures`" % m
                for m in missing]
    bad = []
    tj = _load_json("figs/table1.json")
    rows = tj.get("rows", [])
    tex = (PAPER / "table1.tex").read_text(encoding="utf-8")

    if r"%% paper/table1.tex -- GENERATED" not in tex:
        bad.append("paper/table1.tex has lost its GENERATED banner: it is "
                   "meant to be written whole by paper/table1.py")

    # --- leg 1: the typeset cells are the driver's cells --------------------
    tex_rows = _tex_rows(tex)
    if len(tex_rows) < len(rows):
        bad.append("paper/table1.tex has %d tabular data row(s), "
                   "figs/table1.json carries %d"
                   % (len(tex_rows), len(rows)))
    else:
        body = tex_rows[-len(rows):] if rows else []
        for cells, r in zip(body, rows):
            want = [r["bin"], r["n"], r["amp"], r["err1"], r["err10"],
                    r["significance"]]
            if cells != want:
                bad.append(
                    "paper/table1.tex row %r does not match the cells "
                    "paper/table1.py wrote into figs/table1.json (%r): the "
                    "table has been edited by hand, or the figures were "
                    "rebuilt without rebuilding it"
                    % (" & ".join(cells), " & ".join(want)))

    # --- leg 2: those cells' raw values are the drivers' measurements -------
    f2 = _load_json("figs/fig2.json")
    f4 = _load_json("figs/fig4.json")
    spots = {s["spot"]: s for s in f2.get("spots", [])}
    for r in rows:
        v = r.get("values", {})
        if r["kind"] == "inclusive":
            s = spots.get(r["spot"])
            if s is None:
                bad.append("Table 1 carries inclusive super-bin %r, which "
                           "figs/fig2.json does not measure" % (r["spot"],))
                continue
            want = {"n_1yr": s["n_1yr"], "amp": s["a_truth"],
                    "err_1yr": s["err_1yr"], "err_10yr": s["err_10yr"],
                    "significance_1yr": s["significance_1yr"]}
            where = "figs/fig2.json spot %s" % r["spot"]
        else:
            b = f4["best_bin"]
            want = {"n_1yr": b["n_1yr"], "amp": f4["a2_per_pzz"],
                    "err_1yr": f4["err_1yr"], "err_10yr": f4["err_10yr"],
                    "significance_1yr": abs(f4["a2_per_pzz"]
                                            / f4["err_1yr"])}
            where = "figs/fig4.json"
        for k, wanted in want.items():
            got = v.get(k)
            if got is None or abs(float(got) - float(wanted)) > \
                    1e-9 * max(1.0, abs(float(wanted))):
                bad.append("Table 1 %s = %r for the %s row, but %s measures "
                           "%r: Table 1 is stale against the figures"
                           % (k, got, r["kind"], where, wanted))

    # --- leg 3: the table's own footing is the figures' ---------------------
    for key, src_obj, src_name in (("pzz", f2["settings"], "figs/fig2.json"),
                                   ("lumi_1yr", f2["settings"], "figs/fig2.json"),
                                   ("lumi_10yr", f2["settings"], "figs/fig2.json")):
        if key in tj and key in src_obj and \
                abs(float(tj[key]) - float(src_obj[key])) > 1e-12:
            bad.append("figs/table1.json %s = %r against %s's %r"
                       % (key, tj[key], src_name, src_obj[key]))
    return bad


def _provenance_of_built_figures():
    """Each figN.json names the producing script and published figure that
    figs/README.md registers for that figure."""
