"""The `paper/` scaffold and its bibliography stay internally consistent.

Motivated by plans/07 SS 7.8, whose definition of done for the letter asks for
two mechanical things this module supplies:

  * "Every citation BibTeX-verified against INSPIRE" -- the acceptance the
    run-19 ledger wrote as "a new checker prints `0 unresolved` over
    paper/refs.bib" (T27).  Three things are counted as unresolved, and the
    standalone line prints their sum.  Two of them make refs.bib and the
    letter's `\cite` commands an exact correspondence: a `\cite` key in
    main.tex with no entry in refs.bib, and an entry in refs.bib that no
    `\cite` reaches.  The second of those is why refs.bib holds the letter's
    35 works alone: the 40 further records that cover the source reference
    lists live in refs_reserve.bib, which only draft mode compiles, and
    promoting one is a move between the two files.  The third walks the
    numbered reference lists of Report 1 and of the coherent note -- the two
    documents plans/07 WP6 says the letter's text is drafted from -- and
    asserts that every numbered entry of both is represented by at least one
    record in the two files together.  That mapping is carried in the files
    themselves, as a `% cited by R1[n]/N[m]` comment above every entry;
  * "Four letter figures + Table 1 regenerated by one `paper/` build script"
    (T25).  Two legs.  The register in `paper/figs/README.md` must point at
    producing scripts that are really there; and, now that the drivers exist,
    the build products must be present and Table 1 must still be the table
    those drivers would write.  The second leg is what makes "every number in
    Table 1 was produced by a driver" mechanical rather than a promise:
    `paper/table1.tex` is compared cell by cell with `paper/figs/table1.json`,
    and every raw value behind those cells is compared with the measurement it
    claims to come from in `figs/fig2.json` or `figs/fig4.json`.  Hand-editing
    the table, or rebuilding the figures without rebuilding the table, fails
    the sweep.

Scope, and what this module deliberately does NOT do.

  * It never touches the network.  `refs.bib` was fetched from INSPIRE once, by
    a one-off fetcher under the run-19 scratchpad, and `paper/refs_provenance.md`
    is that fetch's audit trail.  Re-querying INSPIRE on every consistency sweep
    would make the sweep slow, flaky and dependent on a third party's uptime, so
    what is checked here is the *shape* of the result: an entry either looks
    like a machine-fetched INSPIRE record or says in a `note` field that it was
    written by hand.
  * It does not check volumes and page numbers.  plans/07 SS 7.3 row 10 puts
    that re-verification at submission, not at scaffolding time, and six of the
    entries are 2025-2026 preprints whose journal data have not settled.
  * It does not check the letter's physics.  What it checks about the numbers
    the letter puts in front of a reader without a sentence around them --
    Table 1, its caption and the abstract -- is that each of them is a number
    the programme has already published: every one is declared in the
    `SOURCED` table below against the string Report 1's template or the
    manual's expected-numbers table (docs/reproduction_manual.md SS 7) prints
    it in, that string must still be in that document verbatim, and the
    letter's own value must agree with a number inside it to the precision
    that number is printed at.  A number that is in neither document is
    declared against the driver that measured it, with the reason; there are
    five of those and they are listed in the table.  Adding a number to the
    abstract or to Table 1 without declaring it fails the sweep, as does
    editing one of the two documents so that the string it was read out of is
    gone.  What it checks about the rest of the text (T26/T28) is weaker --
    that every number in it is *attributed*: `paper/main.tex`
    carries a "% src:" comment on every body line that quotes a number, and on
    the line above every displayed equation, naming the report section, plan
    section or build artifact the number comes from.  A number with no source
    comment fails the sweep; whether the source says what the sentence says is
    a reading, not a grep, and belongs to the author.
  * It refuses, in `main.tex` and `paper/cover_letter.md`, any form retired in
    `tools/retired_numbers.json`.  `tools/checks/retired_strings.py` owns that
    list but its corpus is the reports, the plans, the docs and the module
    docstrings of `evgen/` and `fastsim/`; `paper/` is outside it, and a letter
    that quoted a withdrawn number would pass every other check in the tree.

Standalone use (this is the T27 acceptance line):

    python3 tools/checks/paper_numbers.py
"""

