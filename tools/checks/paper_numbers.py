# --- the letter's text (T26 / T28) -----------------------------------------

# Structural lines whose digits are not quoted quantities: the class line, the
# package list, the title and address, the float machinery, the bibliography.
_STRUCTURAL = re.compile(
    r"^\s*\\(documentclass|usepackage|PassOptionsToPackage|graphicspath|input|"
    r"includegraphics|newif|draftbib|journal|title|author|address|keyword|"
    r"bibliographystyle|bibliography|label|emergencystretch|Urlmuskip|"
    r"begin|end|caption|centering|section|maketitle)\b")

# Digits that carry no measurement and are removed before the test: citation
# and reference keys, isotope and power superscripts, subscripts, and control
# sequences (\Delta, \times, \sigma).
_NON_NUMERIC = [
    re.compile(r"\\(?:cite|ref|label|input|includegraphics|newcommand)\s*"
               r"(?:\[[^\]]*\])?\{[^}]*\}"),
    re.compile(r"[\^_]\s*\{[^{}]*\}"),        # ^{6}, _{zz}, ^{-1}, ^{33}
    re.compile(r"[\^_]\s*\\?\w"),             # ^2, _m
    re.compile(r"\\[a-zA-Z]+"),               # \Delta, \times, \sigma
]

# What survives that stripping is then tested for a QUANTITY rather than for a
# digit.  A quoted quantity is a decimal, a number of two digits or more, or a
# percentage; a bare single digit is notation -- "spin-1", "IP6", "PYTHIA 8",
# "cos 2phi", "A > 2", "Section 3", "(1,-2,1)" -- and carries nothing to
# source.  Numbers written as powers of ten survive as their mantissa (the
# exponent is a stripped superscript), so 5.2e9 and 1e-3 are both caught.
_QUANTITY = re.compile(r"\d+\.\d|\d{2,}|\d+\s*\\%")

# What a "% src:" comment has to name.  Every token is a place in this
# repository a number can be read out of.
_SRC = re.compile(
    r"(?:R[0-4]\s+(?:sec\s+[0-9][0-9A-Za-z.]*|Table\s+\d+|Appendix\s+A)"
    r"|note\s+sec\s+\d+"
    r"|manual\s+sec\s+[0-9.]+"
    r"|plans/\d\d\s+sec\s+[0-9.]+"
    r"|figs/(?:fig[1-4]|table1)\.json"
    r"|Table\s+1)")

_FLOAT = re.compile(r"^\s*\\begin\{(figure\*?|table\*?)\}")
_MATH_BEGIN = re.compile(r"^\s*\\begin\{(equation\*?|multline\*?|align\*?|gather\*?)\}")


def _split_comment(line):
    """(code, comment) for one TeX line; comment is '' when there is none."""
    i = 0
    while i < len(line):
        if line[i] == "%" and (i == 0 or line[i - 1] != "\\"):
            return line[:i], line[i + 1:]
        i += 1
    return line, ""


def _quotes_a_number(code):
    s = code
    # a per-cent sign is \% and would lose its digit to the control-sequence
    # rule, so the percentage test runs on the unstripped line
    if re.search(r"\d+\s*\\%", s):
        return True
    for pat in _NON_NUMERIC:
        s = pat.sub(" ", s)
    return bool(_QUANTITY.search(s))


def _text_issues():
    """Every number in the body names where it came from."""
    path = PAPER / "main.tex"
    if not path.exists():
        return ["paper/main.tex is missing"]
    lines = path.read_text(encoding="utf-8").split("\n")

    # the header must say what the document is, and the body must not
    head = "\n".join(lines[:40])
    bad = []
    if DRAFT_MARKER not in head:
        bad.append("paper/main.tex's header comment does not carry %r"
                   % DRAFT_MARKER)

    try:
        start = next(i for i, l in enumerate(lines)
                     if l.strip().startswith(r"\begin{document}"))
    except StopIteration:
        return bad + [r"paper/main.tex has no \begin{document}"]

    depth_float = 0
    depth_math = 0
    in_front = False             # \title, \author, \address, \keyword
    in_abstract = False
    pending_src = False          # a "% src:" comment seen on a recent line
    for n, line in enumerate(lines[start:], start=start + 1):
        code, comment = _split_comment(line)
        # the front matter's digits are a ZIP code and an isotope label, not
        # quoted quantities; its abstract is body text and is checked.
        if r"\begin{frontmatter}" in code:
            in_front = True
        if r"\end{frontmatter}" in code:
            in_front = False
        if r"\begin{abstract}" in code:
            in_abstract = True
        if r"\end{abstract}" in code:
            in_abstract = False
        if in_front and not in_abstract:
            continue
        has_src = "src:" in comment and _SRC.search(comment) is not None
        if not code.strip():
            if has_src:
                pending_src = True
            continue

        if _FLOAT.search(code):
            depth_float += 1
        if depth_float and re.search(r"\\end\{(figure\*?|table\*?)\}", code):
            depth_float -= 1
            continue
        if depth_float:
            continue            # captions and graphics are generated elsewhere

        if _MATH_BEGIN.search(code):
            if not (has_src or pending_src):
                bad.append("main.tex:%d opens a displayed equation with no "
                           "'%% src:' comment above it" % n)
            depth_math += 1
            pending_src = False
            continue
        if depth_math:
            if re.search(r"\\end\{(equation\*?|multline\*?|align\*?|gather\*?)\}",
                         code):
                depth_math -= 1
            continue

        # the word "draft" belongs in the header, never in the text
        if re.search(r"(?i)\bdrafts?\b", code):
            bad.append("main.tex:%d calls the document a draft in the body; "
                       "that belongs in the header comment only" % n)

        if _STRUCTURAL.search(code):
            pending_src = has_src
            continue
        if _quotes_a_number(code) and not has_src:
            bad.append("main.tex:%d quotes a number with no '%% src:' comment "
                       "naming where it comes from: %r" % (n, code.strip()))
        pending_src = has_src
    return bad


def _abstract_issues():
    path = PAPER / "main.tex"
    if not path.exists():
        return []
    text = path.read_text(encoding="utf-8")
    m = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", text, re.S)
    if not m:
        return [r"paper/main.tex has no abstract environment"]
    body = _strip_tex_comments(m.group(1))
    body = re.sub(r"\$[^$]*\$", "M", body)          # one math span = one word
    body = re.sub(r"\\[a-zA-Z]+\*?", " ", body)
    body = body.replace("{", " ").replace("}", " ").replace("~", " ")
    n = len(body.split())
    if n > MAX_ABSTRACT_WORDS:
        return ["paper/main.tex's abstract is %d words; the letter budgets "
                "at most %d" % (n, MAX_ABSTRACT_WORDS)]
    return []


