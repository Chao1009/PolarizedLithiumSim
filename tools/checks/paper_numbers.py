def _significant(text):
    """The significant digits of a printed decimal: 0.60 -> '60', 1.90 ->
    '190', 0.0013 -> '13'.  Trailing zeros after a point are significant."""
    s = text.strip().lstrip("+-\u2212")
    s = s.replace(".", "") if "." in s else s
    s = s.lstrip("0")
    return s or "0"


def _rounded(value, k):
    """`value` as k significant digits, as a digit string."""
    if k < 1:
        return ""
    return ("%.*e" % (k - 1, abs(float(value)))).split("e")[0].replace(".", "")


def _agrees(literal, value, printed, slack=0):
    """Does the letter's number agree with a number the source prints?

    The comparison is on significant digits and ignores the power of ten:
    Report 1 factors it out of a list ("1.7, 1.4, 2.7 and 4.5 x10^-4") and the
    letter factors it into a column heading ("[10^-3]"), so the scales are not
    comparable as printed while the digits are.  Where the letter's raw value
    is known it is rounded to the source's precision, which is the honest
    comparison: the source's 2.7 is 2.7496e-4 rounded, and so is the letter's
    0.275, but rounding 0.275 again would give 2.8.
    """
    kp = len(_significant(printed))
    if value is None:
        k = min(kp, len(_significant(literal)))
        mine = _rounded(float(literal), k)
    else:
        k = kp
        mine = _rounded(value, k)
    if not k:
        return False
    theirs = _rounded(float(printed), k)
    if mine == theirs:
        return True
    # a declared slack is one unit in the last digit the source printed
    return slack and len(mine) == len(theirs) \
        and abs(int(mine) - int(theirs)) <= slack


def _flatten_html(text):
    import html as _html
    text = re.sub(r"<script.*?</script>", " ", text, flags=re.S)
    tex = " ".join(re.findall(r'data-tex="([^"]*)"', text))
    body = re.sub(r"<[^>]+>", " ", text)
    return re.sub(r"\s+", " ", _html.unescape(body) + " "
                  + _html.unescape(tex))


def _source_text(which):
    """The flattened text of one source document, or None."""
    path = ROOT / _SOURCE_FILE[which]
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    if which == "R1":
        return _flatten_html(text)
    if MANUAL_SECTION not in text:
        return None
    body = text[text.index(MANUAL_SECTION):]
    if MANUAL_SECTION_END in body:
        body = body[:body.index(MANUAL_SECTION_END)]
    return re.sub(r"\s+", " ", body)


def _number_source_issues():
    """Every number of Table 1, its caption and the abstract is declared, and
    every declaration still holds."""
    quantities = _letter_quantities()
    if not quantities:
        return ["paper/figs/table1.json and paper/main.tex quote no numbers: "
                "run `bash paper/build.sh --figures`"]
    declared = {}
    bad = []
    for row in SOURCED:
        where, role, lit, source, printed = row[:5]
        slack_note = row[5] if len(row) > 5 else None
        if (where, role, lit) in declared:
            bad.append("SOURCED declares %s / %s / %s twice"
                       % (where, role, lit))
        declared[(where, role, lit)] = (source, printed, slack_note)
    corpus = {}
    used = set()
    for where, role, lit, value in quantities:
        entry = declared.get((where, role, lit))
        if entry is None:
            bad.append("the letter's %s quotes %s (%s), which is declared in "
                       "no source: add it to SOURCED in "
                       "tools/checks/paper_numbers.py against the string "
                       "Report 1 or the manual prints it in"
                       % (where, lit, role))
            continue
        used.add((where, role, lit))
        source, printed, slack_note = entry
        if source == "drivers":
            if not printed:
                bad.append("%s / %s is declared against the drivers with no "
                           "reason" % (where, lit))
            continue
        if source not in corpus:
            corpus[source] = _source_text(source)
        text = corpus[source]
        if text is None:
            bad.append("cannot read %s, the source declared for the %s of %s"
                       % (_SOURCE_FILE[source], lit, where))
            continue
        if printed not in text:
            bad.append("%s no longer carries %r, which the %s of the letter's "
                       "%s is read out of" % (_SOURCE_FILE[source], printed,
                                              lit, where))
            continue
        numbers = _TEX_NUMBER.findall(printed)
        slack = 1 if slack_note else 0
        if not any(_agrees(lit, value, n, slack) for n in numbers):
            bad.append("the letter's %s quotes %s in %s, which does not agree "
                       "with any number in %r (%s)"
                       % (where, lit, role, printed, _SOURCE_FILE[source]))
        elif slack and any(_agrees(lit, value, n) for n in numbers):
            bad.append("%s / %s / %s carries a declared slack it no longer "
                       "needs: it now agrees exactly, so drop the sixth field"
                       % (where, role, lit))
    for key in declared:
        if key not in used:
            bad.append("SOURCED declares %s / %s / %s, which the letter no "
                       "longer quotes: drop the row" % key)
    return bad


